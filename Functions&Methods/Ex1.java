// Basic Structure of a Function (Method)

class Ex1{
    static void greet(){
        System.out.println("Hello");
    }
    public static void main(String args[])
    {
        greet();    //function call
    }
}




// Breakdown:

// static → class ke through call hoga (object ki need nahi)

// void → koi value return nahi karega

// greet() → function name

// { } → function body

// greet(); → function call